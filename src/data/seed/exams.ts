const sec = (title: string, topics: string[]): SyllabusSection => ({ title, topics });

const row = (
  stage: string,
  subject: string,
  questions: number,
  marks: number,
  duration: string,
  negative_marking: string,
): ExamPatternRow => ({ stage, subject, questions, marks, duration, negative_marking });

const week = (week: number, focus: string, tasks: string[]): StudyPlanWeek => ({ week, focus, tasks });

/** Questions tagged for the exam first, topped up from the listed subjects so every exam has 6–8. */
function pickQuestions(examId: string, subjects: string[], count = 8): string[] {
  const own = questionIds((q) => q.exam_id === examId);
  const seen = new Set(own);
  const extra = questionIds((q) => subjects.includes(q.subject_id) && !seen.has(q.id));
  return [...own, ...extra].slice(0, count);
}

